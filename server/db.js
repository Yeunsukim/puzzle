async function openPostgres() {
  const { default: pg } = await import('pg');
  // 큰 숫자(BIGINT)·합계(NUMERIC)를 글자가 아니라 숫자로 받기
  pg.types.setTypeParser(20, v => parseInt(v, 10));
  pg.types.setTypeParser(1700, v => parseFloat(v));
  const local = /@(localhost|127\.0\.0\.1)[:/]/.test(DATABASE_URL);
  const pool = new pg.Pool({
    connectionString: DATABASE_URL,
    ssl: local ? false : { rejectUnauthorized: false },
    max: Number(process.env.PG_POOL_MAX) || 5,
    idleTimeoutMillis: 20000,
    keepAlive: true,
  });
  pool.on('error', err => console.error('데이터베이스 연결 문제:', err.message));
  const conv = sql => { let i = 0; return sql.replace(/\?/g, () => '$' + (++i)); };
  // 인터넷 연결이 잠깐 끊겼으면 한 번 더 시도한다
  const RETRY = new Set(['ECONNRESET', 'ETIMEDOUT', 'EPIPE', 'ECONNREFUSED', '57P01', '08006', '08003']);
  const q = async (sql, p) => {
    try { return await pool.query(conv(sql), p); }
    catch (err) {
      if (!RETRY.has(err.code) && !/Connection terminated/i.test(err.message)) throw err;
      await new Promise(r => setTimeout(r, 300));
      return pool.query(conv(sql), p);
    }
  };
  const db = {
    kind: 'supabase',
    async get(sql, ...p) { return (await q(sql, p)).rows[0] || null; },
    async all(sql, ...p) { return (await q(sql, p)).rows; },
    async run(sql, ...p) { return { changes: (await q(sql, p)).rowCount }; },
    async exec(sql) { await pool.query(sql); },
  };
  await db.exec(PG_SCHEMA);
  return db;
}

async function openSqlite() {
  const { DatabaseSync } = await import('node:sqlite');
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const s = new DatabaseSync(path.join(DATA_DIR, 'puzzle.db'));
  s.exec(SQLITE_SCHEMA);
  // 예전 데이터베이스에 없던 칸 추가
  const hasCol = (t, c) => s.prepare(`PRAGMA table_info(${t})`).all().some(x => x.name === c);
  if (!hasCol('pictures', 'category')) s.exec("ALTER TABLE pictures ADD COLUMN category TEXT NOT NULL DEFAULT 'mine'");
  if (!hasCol('users', 'friend_code')) s.exec('ALTER TABLE users ADD COLUMN friend_code TEXT');
  const plain = r => (r ? { ...r } : null);
  return {
    kind: 'sqlite',
    async get(sql, ...p) { return plain(s.prepare(sql).get(...p)); },
    async all(sql, ...p) { return s.prepare(sql).all(...p).map(plain); },
    async run(sql, ...p) { return { changes: Number(s.prepare(sql).run(...p).changes) }; },
    async exec(sql) { s.exec(sql); },
  };
}

export const db = DATABASE_URL ? await openPostgres() : await openSqlite();

